#!/usr/bin/env bash
# Regenerates docker/docker-compose.<env>.yml from apps/*/docker-compose.<env>.yml, then runs compose
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."
env="$1"
shift
out="docker/docker-compose.${env}.yml"

{
  echo "# Generated by docker/compose.sh; do not edit"
  echo "name: realtime-chat-app"
  echo
  echo "include:"
  for file in apps/*/docker-compose."${env}".yml; do
    [ -e "$file" ] && echo "  - ../${file}"
  done
} >"$out"

exec docker compose -f "$out" "$@"
